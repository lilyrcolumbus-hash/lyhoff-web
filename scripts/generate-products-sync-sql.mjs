// One-time generator: reads the current lib/products.ts catalog and writes
// supabase/sync-products.sql — an idempotent INSERT ... ON CONFLICT (slug) DO
// UPDATE script the owner pastes into the Supabase SQL Editor herself (same
// pattern as every other one-time supabase/*.sql in this repo). Safe to
// re-run any time lib/products.ts changes and the table needs to catch up,
// until /admin + fetch-products.mjs replace lib/products.ts as the source of
// truth entirely.
//
// Run: node scripts/generate-products-sync-sql.mjs

import fs from "node:fs";

const UNSPLASH = (id, w = 800, h = 900) =>
  `https://images.unsplash.com/photo-${id}?w=${w}&h=${h}&q=90&auto=format&fit=crop`;

const tsSrc = fs.readFileSync(new URL("../lib/products.ts", import.meta.url), "utf8");
const match = tsSrc.match(/export const products: Product\[\] = (\[[\s\S]*?\n\]);/);
if (!match) throw new Error("Could not find `products` array in lib/products.ts");
// eslint-disable-next-line no-eval -- trusted local file, one-time build-time script
const products = eval(match[1]);

const COLUMNS = [
  "asin", "slug", "category", "name", "tagline", "description", "ingredients",
  "price", "size", "image", "badge", "active", "variant_group", "scent",
  "scent_group", "benefits", "gift", "how_to_use", "reviews",
];

const camelToRow = (p) => ({
  asin: p.asin, slug: p.slug, category: p.category, name: p.name, tagline: p.tagline,
  description: p.description, ingredients: p.ingredients ?? [], price: p.price, size: p.size,
  image: p.image, badge: p.badge ?? null, active: p.active,
  variant_group: p.variantGroup ?? null, scent: p.scent ?? null, scent_group: p.scentGroup ?? null,
  benefits: p.benefits ?? [], gift: p.gift ?? null, how_to_use: p.howToUse, reviews: p.reviews ?? [],
});

const sqlLiteral = (col, value) => {
  if (value === null || value === undefined) return "null";
  if (col === "price") return String(value);
  if (col === "active") return value ? "true" : "false";
  if (["name", "tagline", "description", "ingredients", "badge", "benefits", "gift", "how_to_use", "reviews"].includes(col)) {
    return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  }
  return `'${String(value).replace(/'/g, "''")}'`;
};

const rows = products.map(camelToRow);
const valuesSql = rows
  .map((row) => `  (${COLUMNS.map((c) => sqlLiteral(c, row[c])).join(", ")})`)
  .join(",\n");

const updateSet = COLUMNS.filter((c) => c !== "slug")
  .map((c) => `  ${c} = excluded.${c}`)
  .join(",\n");

const sql = `-- Auto-generated by scripts/generate-products-sync-sql.mjs from the current
-- lib/products.ts catalog — run this in the Supabase SQL Editor to bring the
-- \`products\` table in sync with the code. Safe to re-run (upsert by slug).
-- Regenerate whenever lib/products.ts changes and the table needs to catch up.

insert into public.products (${COLUMNS.join(", ")})
values
${valuesSql}
on conflict (slug) do update set
${updateSet};
`;

fs.writeFileSync(new URL("../supabase/sync-products.sql", import.meta.url), sql);
console.log(`Wrote supabase/sync-products.sql — ${rows.length} products.`);
